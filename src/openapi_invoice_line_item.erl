-module(openapi_invoice_line_item).

-export([encode/1]).

-export_type([openapi_invoice_line_item/0]).

-type openapi_invoice_line_item() ::
    #{ 'article_number' => binary(),
       'description' := binary(),
       'discount_amount' => binary(),
       'discount_percentage' => binary(),
       'input_vat_deductible' => boolean(),
       'input_vat_rate' => binary(),
       'is_intra_community_acquisition' => boolean(),
       'is_margin_25a' => boolean(),
       'ledger_account' => binary(),
       'line_total' := binary(),
       'line_total_gross' => binary(),
       'margin_25a_purchase_price' => binary(),
       'meter_point_id' => openapi_u_uid:openapi_u_uid(),
       'position' := integer(),
       'price_components' => openapi_any_type:openapi_any_type(),
       'product_id' => openapi_u_uid:openapi_u_uid(),
       'product_sku' => binary(),
       'quantity' := binary(),
       'supplier_article_number' => binary(),
       'tax_rate' => binary(),
       'unit' := openapi_any_type:openapi_any_type(),
       'unit_price' := binary(),
       'usage_data_id' => openapi_u_uid:openapi_u_uid(),
       'vat_rate_nominal' => binary(),
       'vat_special_case' => binary()
     }.

encode(#{ 'article_number' := ArticleNumber,
          'description' := Description,
          'discount_amount' := DiscountAmount,
          'discount_percentage' := DiscountPercentage,
          'input_vat_deductible' := InputVatDeductible,
          'input_vat_rate' := InputVatRate,
          'is_intra_community_acquisition' := IsIntraCommunityAcquisition,
          'is_margin_25a' := IsMargin25a,
          'ledger_account' := LedgerAccount,
          'line_total' := LineTotal,
          'line_total_gross' := LineTotalGross,
          'margin_25a_purchase_price' := Margin25aPurchasePrice,
          'meter_point_id' := MeterPointId,
          'position' := Position,
          'price_components' := PriceComponents,
          'product_id' := ProductId,
          'product_sku' := ProductSku,
          'quantity' := Quantity,
          'supplier_article_number' := SupplierArticleNumber,
          'tax_rate' := TaxRate,
          'unit' := Unit,
          'unit_price' := UnitPrice,
          'usage_data_id' := UsageDataId,
          'vat_rate_nominal' := VatRateNominal,
          'vat_special_case' := VatSpecialCase
        }) ->
    #{ 'article_number' => ArticleNumber,
       'description' => Description,
       'discount_amount' => DiscountAmount,
       'discount_percentage' => DiscountPercentage,
       'input_vat_deductible' => InputVatDeductible,
       'input_vat_rate' => InputVatRate,
       'is_intra_community_acquisition' => IsIntraCommunityAcquisition,
       'is_margin_25a' => IsMargin25a,
       'ledger_account' => LedgerAccount,
       'line_total' => LineTotal,
       'line_total_gross' => LineTotalGross,
       'margin_25a_purchase_price' => Margin25aPurchasePrice,
       'meter_point_id' => MeterPointId,
       'position' => Position,
       'price_components' => PriceComponents,
       'product_id' => ProductId,
       'product_sku' => ProductSku,
       'quantity' => Quantity,
       'supplier_article_number' => SupplierArticleNumber,
       'tax_rate' => TaxRate,
       'unit' => Unit,
       'unit_price' => UnitPrice,
       'usage_data_id' => UsageDataId,
       'vat_rate_nominal' => VatRateNominal,
       'vat_special_case' => VatSpecialCase
     }.
